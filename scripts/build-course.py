"""Bundle authored lesson JSON as static JS; metadata is not completed teaching content."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
from verb_build import load_verbs, expand_lesson, validate_references, write_bundle
from grammar_build import load_grammar, expand_grammar, write_grammar
grammar = load_grammar()
write_grammar(grammar)
verbs = load_verbs()
authored_lessons = {}
catalog = json.loads((ROOT / 'lessons/catalog.json').read_text(encoding='utf-8'))
lessons = []
for entry in catalog:
    source = ROOT / 'lessons' / f"{entry['number']:02}.json"
    if source.exists():
        data = json.loads(source.read_text(encoding='utf-8'))
        assert data['number'] == entry['number']
        authored_lessons[data['number']] = data
        lessons.append({**entry, **expand_lesson(expand_grammar(data,grammar), verbs['records'])})
validate_references(verbs, authored_lessons)
write_bundle(verbs)
content = {'catalog': catalog, 'lessons': lessons}
(ROOT / 'course.js').write_text('// Generated by scripts/build-course.py from lessons/*.json.\nwindow.COURSE_LIBRARY = ' + json.dumps(content, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print(f"Bundled {len(lessons)} authored lessons and {len(verbs['records'])} shared present-tense entries.")
(ROOT / 'lesson14.js').write_text(r'''// Generated compatibility alias; author lesson 14 in lessons/14.json.
window.LESSON14_CONTENT = window.COURSE_LIBRARY.lessons.find(lesson => lesson.number === 14);
window.LESSON14_CONTENT.exercises = [...window.LESSON14_CONTENT.sections.find(s => s.id === 'practice').html.matchAll(/<h3>([A-J])\. (.*?)<\/h3>([\s\S]*?)(?=<h3>|$)/g)].map(([,id,title,body]) => ({id,title,html:`<h3>${id}. ${title}</h3>${body}`}));
''', encoding='utf-8')

import runpy
runpy.run_path(str(ROOT/'scripts/build-skills.py'))

# Content fingerprints avoid showing a cached, older course bundle after publishing.
import hashlib
import re
index = ROOT / 'index.html'
page = index.read_text(encoding='utf-8')
for asset in ['grammar-data.js', 'verb-data.js', 'verb-knowledge.js', 'verb-knowledge.css', 'styles.css', 'content.js', 'course.js', 'lesson14.js', 'app.js', 'knowledge-map.js', 'knowledge-map.css', 'skill-tree-data.js', 'skill-tree.js', 'skill-tree.css']:
    digest = hashlib.sha256((ROOT / asset).read_bytes()).hexdigest()[:12]
    page = re.sub(r'(["\'])' + re.escape(asset) + r'(?:\?v=[a-f0-9]+)?(["\'])',
                  lambda match: match[1] + asset + '?v=' + digest + match[2], page)
index.write_text(page, encoding='utf-8')

